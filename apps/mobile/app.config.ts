import type { ConfigContext, ExpoConfig } from 'expo/config';

// Permission prompts are UI copy. Imported by path with its extension because
// the config is loaded by Node, outside Metro and the workspace package.
import { permissionCopy } from '../../packages/shared/src/copy/permissions.ts';
// The splash and the adaptive icon sit on the accent (D26): the mark is white.
import { palette } from '../../packages/shared/src/design/tokens.ts';
// iOS 27 SDK: the app must adopt the UIScene life cycle (F11, docs/release.md).
import withIosSceneLifecycle from './plugins/with-ios-scene-lifecycle.ts';

// Carrier and operator app (D06). Native config lives here (Continuous Native
// Generation): `ios/` and `android/` are generated by `expo prebuild` and are
// not committed. Every external value comes from the environment (.env.example)
// so the app builds without accounts; EAS and push need EXPO_PUBLIC_EAS_PROJECT_ID.
const easProjectId = process.env.EXPO_PUBLIC_EAS_PROJECT_ID || undefined;
const bundleId = process.env.APP_BUNDLE_ID || 'mx.transport.app';

// Sentry (B25): the SDK reports only with EXPO_PUBLIC_SENTRY_DSN (src/lib/sentry.ts).
// Its config plugin uploads source maps and debug symbols in native builds, so
// it is added only when the build has the credentials for it (EAS, B27);
// otherwise the build would fail trying to upload.
const sentryUpload =
  process.env.SENTRY_AUTH_TOKEN && process.env.SENTRY_ORG && process.env.SENTRY_PROJECT
    ? [
        [
          '@sentry/react-native/expo',
          { organization: process.env.SENTRY_ORG, project: process.env.SENTRY_PROJECT },
        ] as [string, Record<string, string>],
      ]
    : [];

// Universal links of the trip link (H2, D29): https://<sitio>/viaje/<token>
// opens the app when the site is configured (https only) and the web serves
// apple-app-site-association / assetlinks.json (APPLE_TEAM_ID,
// ANDROID_CERT_SHA256). Without it the page offers "Abrir en la app" with the
// deep link. Changing it needs a new native build.
const siteHost = (() => {
  try {
    const url = new URL(process.env.EXPO_PUBLIC_SITE_URL ?? '');
    return url.protocol === 'https:' ? url.host : null;
  } catch {
    return null;
  }
})();

// withIosSceneLifecycle wraps the whole config (ExpoConfig's `plugins` only
// types module names, not plugin functions).
export default ({ config }: ConfigContext): ExpoConfig =>
  withIosSceneLifecycle({
    ...config,
    name: 'Transport',
    slug: 'transport',
    scheme: 'transport',
    version: '0.1.0',
    orientation: 'portrait',
    icon: './assets/icon.png',
    // Light, dark or the phone's (D26): the app follows the theme the person picks.
    userInterfaceStyle: 'automatic',
    runtimeVersion: { policy: 'appVersion' },
    ios: {
      bundleIdentifier: bundleId,
      supportsTablet: false,
      config: { usesNonExemptEncryption: false },
      ...(siteHost ? { associatedDomains: [`applinks:${siteHost}`] } : {}),
    },
    android: {
      package: bundleId,
      adaptiveIcon: {
        backgroundColor: palette.light.accent,
        foregroundImage: './assets/android-icon-foreground.png',
        backgroundImage: './assets/android-icon-background.png',
        monochromeImage: './assets/android-icon-monochrome.png',
      },
      // Session tokens live in the Keychain/Keystore; never back them up.
      allowBackup: false,
      ...(siteHost
        ? {
            intentFilters: [
              {
                action: 'VIEW',
                autoVerify: true,
                data: [{ scheme: 'https', host: siteHost, pathPrefix: '/viaje/' }],
                category: ['BROWSABLE', 'DEFAULT'],
              },
            ],
          }
        : {}),
    },
    plugins: [
      'expo-router',
      'expo-secure-store',
      'expo-notifications',
      // Documents (B18): photos of documents from the camera or the library.
      [
        'expo-image-picker',
        {
          cameraPermission: permissionCopy.camera,
          photosPermission: permissionCopy.photos,
          microphonePermission: false,
        },
      ],
      // Trip status events keep where they happened (B21), and during an active
      // trip the location is shared in the background (B22, after the consent
      // screen). iOS: adds `location` to UIBackgroundModes and the "Always"
      // purpose string. Android: ACCESS_BACKGROUND_LOCATION and a location
      // foreground service with its persistent notification.
      [
        'expo-location',
        {
          locationWhenInUsePermission: permissionCopy.locationWhenInUse,
          locationAlwaysAndWhenInUsePermission: permissionCopy.locationAlways,
          isIosBackgroundLocationEnabled: true,
          isAndroidBackgroundLocationEnabled: true,
          isAndroidForegroundServiceEnabled: true,
        },
      ],
      // Local queue of GPS points (B22).
      'expo-sqlite',
      [
        'expo-splash-screen',
        {
          backgroundColor: palette.light.accent,
          image: './assets/splash-icon.png',
          imageWidth: 96,
          dark: { backgroundColor: palette.dark.bg, image: './assets/splash-icon.png' },
        },
      ],
      ...sentryUpload,
    ],
    extra: easProjectId ? { eas: { projectId: easProjectId } } : {},
  });
