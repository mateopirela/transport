import type { ConfigPlugin, InfoPlist } from 'expo/config-plugins.js';
import { withAppDelegate, withInfoPlist } from 'expo/config-plugins.js';

// iOS 27 SDK (F11): apps built with it must adopt the UIScene life cycle or
// UIKit stops them at launch ("UIScene life cycle is required for apps built
// with this SDK"). Expo 57 ships the scene delegate (`ExpoAppSceneDelegate`,
// exported to Objective-C as `EXExpoAppSceneDelegate`), but the AppDelegate its
// prebuild template generates still creates the window from UIScreen and the
// Info.plist declares no scene manifest. This plugin:
//   1. makes the AppDelegate an `ExpoReactNativeFactoryProvider` and drops the
//      block that creates the window and starts React Native (the scene
//      delegate does both, and forwards URLs and user activities back to the
//      AppDelegate, so deep links keep reaching RCTLinkingManager);
//   2. declares `UIApplicationSceneManifest` with that scene delegate.
// It is idempotent, and it throws when the generated AppDelegate no longer has
// the expected shape: that is the signal that Expo changed its template (for
// example, adopted scenes by default) and this plugin should be revisited or
// removed.

const PLUGIN = 'with-ios-scene-lifecycle';

/** Marks an AppDelegate this plugin already transformed. */
export const APP_DELEGATE_MARKER = `// ${PLUGIN}: React Native starts from ExpoAppSceneDelegate (UIScene life cycle).`;

export const SCENE_DELEGATE_CLASS = 'EXExpoAppSceneDelegate';

export const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: 'Default',
        UISceneDelegateClassName: SCENE_DELEGATE_CLASS,
      },
    ],
  },
};

const CLASS_DECLARATION = /^([ \t]*class AppDelegate: ExpoAppDelegate)( \{)/m;

// The template's window block inside didFinishLaunchingWithOptions:
//   #if os(iOS) || os(tvOS)
//       window = UIWindow(frame: UIScreen.main.bounds)
//       factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
//   #endif
const WINDOW_BLOCK =
  /^[ \t]*#if os\(iOS\) \|\| os\(tvOS\)[ \t]*\n[ \t]*window = UIWindow\(frame: UIScreen\.main\.bounds\)[ \t]*\n[ \t]*factory\.startReactNative\(\s*withModuleName: "main",\s*in: window,\s*launchOptions: launchOptions\s*\)[ \t]*\n[ \t]*#endif[ \t]*\n/m;

// Members ExpoReactNativeFactoryProvider requires; the template declares both.
const REQUIRED_MEMBERS = [
  /^\s*var window: UIWindow\?\s*$/m,
  /^\s*var reactNativeFactory: RCTReactNativeFactory\?\s*$/m,
];

function unexpectedShape(detail: string): Error {
  return new Error(
    `[${PLUGIN}] The AppDelegate.swift generated by expo prebuild no longer has the expected shape: ${detail}. ` +
      'If Expo now adopts the UIScene life cycle by default, remove this plugin from app.config.ts; ' +
      'otherwise update apps/mobile/plugins/with-ios-scene-lifecycle.ts (see docs/release.md).',
  );
}

/** Turns the Expo 57 template AppDelegate into one started by the scene delegate. */
export function adoptSceneLifecycleInAppDelegate(contents: string): string {
  if (contents.includes(APP_DELEGATE_MARKER)) return contents;

  if (contents.includes('ExpoReactNativeFactoryProvider')) {
    throw unexpectedShape('it already conforms to ExpoReactNativeFactoryProvider');
  }
  if (!CLASS_DECLARATION.test(contents)) {
    throw unexpectedShape('"class AppDelegate: ExpoAppDelegate {" not found');
  }
  if (!WINDOW_BLOCK.test(contents)) {
    throw unexpectedShape(
      'the block that creates the window from UIScreen and calls factory.startReactNative was not found',
    );
  }
  for (const member of REQUIRED_MEMBERS) {
    if (!member.test(contents)) {
      throw unexpectedShape(`missing member matching ${member.source}`);
    }
  }

  return contents
    .replace(CLASS_DECLARATION, `$1, ExpoReactNativeFactoryProvider$2\n  ${APP_DELEGATE_MARKER}`)
    .replace(WINDOW_BLOCK, '');
}

// Structural equality for plist values; key order does not matter (plists
// written to disk come back with their keys sorted).
function sameValue(a: unknown, b: unknown): boolean {
  if (Array.isArray(a) || Array.isArray(b)) {
    return (
      Array.isArray(a) &&
      Array.isArray(b) &&
      a.length === b.length &&
      a.every((item, i) => sameValue(item, b[i]))
    );
  }
  if (a && b && typeof a === 'object' && typeof b === 'object') {
    const aKeys = Object.keys(a);
    const bRecord = b as Record<string, unknown>;
    return (
      aKeys.length === Object.keys(b).length &&
      aKeys.every(
        (key) => key in bRecord && sameValue((a as Record<string, unknown>)[key], bRecord[key]),
      )
    );
  }
  return a === b;
}

/** Declares the single-window scene manifest that uses Expo's scene delegate. */
export function adoptSceneLifecycleInInfoPlist(plist: InfoPlist): InfoPlist {
  const existing = plist.UIApplicationSceneManifest;
  if (existing !== undefined && !sameValue(existing, SCENE_MANIFEST)) {
    throw new Error(
      `[${PLUGIN}] Info.plist already declares a different UIApplicationSceneManifest. ` +
        'Merge it with the one this plugin sets (apps/mobile/plugins/with-ios-scene-lifecycle.ts) ' +
        'or remove the plugin if Expo now provides it.',
    );
  }
  return { ...plist, UIApplicationSceneManifest: structuredClone(SCENE_MANIFEST) };
}

const withIosSceneLifecycle: ConfigPlugin = (config) => {
  config = withAppDelegate(config, (mod) => {
    if (mod.modResults.language !== 'swift') {
      throw unexpectedShape(`expected a Swift AppDelegate, got ${mod.modResults.language}`);
    }
    mod.modResults.contents = adoptSceneLifecycleInAppDelegate(mod.modResults.contents);
    return mod;
  });
  return withInfoPlist(config, (mod) => {
    mod.modResults = adoptSceneLifecycleInInfoPlist(mod.modResults);
    return mod;
  });
};

export default withIosSceneLifecycle;
